-- An investor reads their own record in any status, so a pending or rejected
-- applicant can still see where they stand.
create policy investors_select_self
  on public.investors for select to authenticated
  using (id = app.current_user_id());

create policy investors_select_admin
  on public.investors for select to authenticated
  using (app.has_permission('investors.view'));

-- An investor may correct their own details only while the application is still
-- theirs to edit. Once it is under review, changes go through an admin.
create policy investors_update_self
  on public.investors for update to authenticated
  using (id = app.current_user_id() and status in ('prospective', 'rejected'))
  with check (id = app.current_user_id() and status in ('prospective', 'rejected', 'submitted'));

create policy investors_update_admin
  on public.investors for update to authenticated
  using (app.has_permission('investors.update'))
  with check (app.has_permission('investors.update'));

-- No INSERT policy: investor records are created only by the application server
-- through the audited, rate-limited application flow.
-- No DELETE policy for anyone: investors are deactivated, never deleted.

create policy investor_status_history_select_self
  on public.investor_status_history for select to authenticated
  using (investor_id = app.current_user_id());

create policy investor_status_history_select_admin
  on public.investor_status_history for select to authenticated
  using (app.has_permission('investors.view'));

